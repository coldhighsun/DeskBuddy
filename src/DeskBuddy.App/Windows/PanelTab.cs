namespace DeskBuddy.App.Windows;

/// <summary>
/// The tabs of the panel window, in the order they appear.
/// </summary>
public enum PanelTab
{
    /// <summary>
    /// The pomodoro timer.
    /// </summary>
    Pomodoro = 0,

    /// <summary>
    /// The to-do list.
    /// </summary>
    Todo = 1,

    /// <summary>
    /// The sticky note.
    /// </summary>
    Note = 2,

    /// <summary>
    /// The settings.
    /// </summary>
    Settings = 3,
}
